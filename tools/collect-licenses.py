"""Collect installed production dependency notices without fetching network data."""
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def collect():
    # Resolve the actual installed graph. Stale package-manager metadata can list
    # packages that are no longer used by the current dependency symlinks.
    raw = subprocess.check_output(['node', '--input-type=module', '-e', r'''
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const root=process.cwd(), result=new Map();
function visit(name, from, optional=false) {
  const req=createRequire(path.join(from,'package.json'));
  let file;
  try { file=req.resolve(`${name}/package.json`); }
  catch {
    try {
      let dir=path.dirname(req.resolve(name));
      while (dir!==path.dirname(dir)) {
        const candidate=path.join(dir,'package.json');
        if(fs.existsSync(candidate) && JSON.parse(fs.readFileSync(candidate)).name===name) {file=candidate;break;}
        dir=path.dirname(dir);
      }
    } catch(e) {if(!optional) throw e;}
  }
  if(!file) {if(optional) return;throw new Error(`Cannot resolve ${name}`);}
  const pkg=JSON.parse(fs.readFileSync(file)), key=`${pkg.name}@${pkg.version}`;
  if(result.has(key)) return;
  result.set(key,{name:pkg.name,versions:[pkg.version],paths:[path.dirname(file)],license:pkg.license ?? 'UNKNOWN'});
  for(const dep of Object.keys(pkg.dependencies ?? {})) visit(dep,path.dirname(file));
  for(const dep of Object.keys(pkg.optionalDependencies ?? {})) visit(dep,path.dirname(file),true);
}
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json')));
for(const dep of Object.keys(pkg.dependencies)) visit(dep,root);
process.stdout.write(JSON.stringify([...result.values()]));
'''], cwd=ROOT, text=True)
    entries = sorted(json.loads(raw), key=lambda item: (item['name'], item['versions']))
    sections = ['THIRD-PARTY NOTICES', '',
                'Conservative inventory of the installed production dependency graph, including',
                'build helpers reachable from that graph; listing does not imply all code is bundled.',
                'Generated by pnpm licenses:collect. Original license texts follow unchanged.', '']
    rows = ['# Third-party notices', '',
            'ChatGo code is MIT licensed. Dependencies and fonts retain their own licenses.',
            'Full dependency notices are distributed in [public/THIRD_PARTY_NOTICES.txt](public/THIRD_PARTY_NOTICES.txt)',
            'and copied into `dist/THIRD_PARTY_NOTICES.txt` during the build.', '',
            '| Dependency | Installed version | License |', '| --- | --- | --- |']
    for entry in entries:
        path = Path(entry['paths'][0])
        files = sorted(p for p in path.iterdir() if p.is_file() and
                       any(token in p.name.lower() for token in ('license', 'licence', 'copying', 'notice')))
        if entry['name'] == '@vue/devtools-api' and not files:
            if entry['versions'] != ['6.6.4']:
                raise RuntimeError('Review the upstream Vue devtools license for the new version')
            files = [ROOT / 'licenses/vue-devtools-api-6.6.4-MIT.txt']
        if entry['name'].startswith('@rollup/rollup-') and not files:
            # Native optional packages use the license shipped by matching Rollup core.
            version = entry['versions'][0]
            files = [ROOT / f'node_modules/.pnpm/rollup@{version}/node_modules/rollup/LICENSE.md']
            if not files[0].is_file():
                files = [ROOT / f'licenses/rollup-{version}-LICENSE.md']
        if not files or any(not p.is_file() for p in files):
            raise RuntimeError(f'Missing original license text: {entry["name"]}')
        versions = ', '.join(entry['versions'])
        rows.append(f'| {entry["name"]} | {versions} | {entry["license"]} |')
        sections.extend(['=' * 72, f'{entry["name"]} {versions}', f'License: {entry["license"]}', ''])
        for file in files:
            sections.extend([f'--- {file.name} ---', file.read_text(), ''])
    rows.extend(['', '## Fonts', '',
                 '- Bricolage Grotesque: SIL OFL 1.1; see [original notice](public/fonts/BricolageGrotesque-OFL.txt).',
                 '- JetBrains Mono: SIL OFL 1.1; see [original notice](public/fonts/JetBrainsMono-OFL.txt).',
                 '- KaTeX fonts: see the KaTeX MIT notice in the full dependency notices.', '',
                 '## Provenance', '',
                 'The ChatGPT-Voyager MIT notice is preserved in [LICENSE](LICENSE).',
                 'For upstream fallback notice sources, see [licenses/README.md](licenses/README.md).',
                 'Regenerate this inventory after dependency changes with `pnpm licenses:collect`.', ''])
    (ROOT / 'THIRD_PARTY_NOTICES.md').write_text('\n'.join(rows))
    (ROOT / 'public/THIRD_PARTY_NOTICES.txt').write_text('\n'.join(sections))
    (ROOT / 'public/LICENSE').write_text((ROOT / 'LICENSE').read_text())
    print(f'Collected original notices for {len(entries)} dependency packages and project license')


if __name__ == '__main__':
    collect()
